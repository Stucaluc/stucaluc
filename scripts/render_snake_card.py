#!/usr/bin/env python3
"""
Wrap the snake animation generated by Platane/snk inside a custom terminal-style
card that matches the profile header: purple frame, title bar, neon glow on the
snake, a Less -> More legend and a stats footer read from data/contributions.json.

Usage: python scripts/render_snake_card.py dist/snake.svg
Writes assets/snake-card.svg. Run by .github/workflows/update-profile-art.yml.

Class names here use the "k-" prefix so they never clash with the classes the
snake SVG defines (.c, .u, .s).
"""
import json
import os
import re
import sys
from html import escape

HERE = os.path.dirname(__file__)
DATA = os.path.join(HERE, "..", "data", "contributions.json")
OUT = os.path.join(HERE, "..", "assets", "snake-card.svg")

DOTS = ["#1c1830", "#3b1d78", "#5B21B6", "#7C3AED", "#A78BFA"]
SNAKE = "#DDD6FE"
FRAME = "#7C3AED"
MUTED = "#8b85a6"
TEXT = "#c4b5fd"
ACCENT = "#A78BFA"

PAD = 20
TITLE_H = 34
FOOTER_H = 62


def load_snake(path):
    svg = open(path, encoding="utf-8").read()
    svg = re.sub(r"^\s*<\?xml[^>]*\?>", "", svg).strip()
    m = re.match(r"<svg\b([^>]*)>", svg)
    if not m:
        sys.exit("snake file is not an svg")
    attrs = m.group(1)
    vb = re.search(r'viewBox="([^"]+)"', attrs)
    if not vb:
        sys.exit("snake svg has no viewBox")
    vx, vy, vw, vh = (float(v) for v in vb.group(1).split())
    inner = svg[m.end():]
    inner = inner[: inner.rfind("</svg>")]
    return (vx, vy, vw, vh), inner


def render(snake_path):
    (vx, vy, vw, vh), inner = load_snake(snake_path)
    data = json.load(open(DATA, encoding="utf-8"))

    w = int(vw + PAD * 2)
    h = int(TITLE_H + 10 + vh + FOOTER_H)
    sy = TITLE_H + 10

    total = data["total_contributions"]
    active = data["active_days"]
    best = data["best_day"]
    rng = data["range"]

    css = f"""
.k-mono {{ font-family: ui-monospace, SFMono-Regular, Menlo, Consolas, "Liberation Mono", monospace; }}
.k-cur {{ animation: k-blink 1.1s steps(1) infinite; }}
@keyframes k-blink {{ 50% {{ opacity: 0; }} }}
.s {{ filter: drop-shadow(0 0 3px {ACCENT}) drop-shadow(0 0 7px {FRAME}); }}
:root {{ --cs: {SNAKE}; }}
@media (prefers-reduced-motion: reduce) {{ .k-cur {{ animation: none; }} }}
""".strip()

    p = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" '
        f'role="img" aria-label="Snake eating {total} contributions from the last year">',
        f"<desc>Snake by Platane/snk, card by scripts/render_snake_card.py</desc>",
        "<defs>",
        '<linearGradient id="k-bg" x1="0" y1="0" x2="1" y2="1">'
        '<stop offset="0" stop-color="#0f0b1d"/><stop offset="1" stop-color="#0a0a12"/></linearGradient>',
        '<linearGradient id="k-acc" x1="0" y1="0" x2="1" y2="0">'
        '<stop offset="0" stop-color="#5B21B6"/><stop offset=".5" stop-color="#7C3AED"/>'
        '<stop offset="1" stop-color="#A78BFA"/></linearGradient>',
        '<pattern id="k-dots" width="24" height="24" patternUnits="userSpaceOnUse">'
        '<circle cx="2" cy="2" r="1" fill="#A78BFA" fill-opacity=".10"/></pattern>',
        f'<clipPath id="k-clip"><rect width="{w}" height="{h}" rx="14"/></clipPath>',
        "</defs>",
        f"<style>{css}</style>",
        '<g clip-path="url(#k-clip)">',
        f'<rect width="{w}" height="{h}" fill="url(#k-bg)"/>',
        f'<rect width="{w}" height="{h}" fill="url(#k-dots)"/>',
        f'<rect width="{w}" height="3" fill="url(#k-acc)"/>',
        "</g>",
        f'<rect x=".5" y=".5" width="{w-1}" height="{h-1}" rx="14" fill="none" stroke="{FRAME}" stroke-opacity=".35"/>',
        f'<line x1="0" y1="{TITLE_H}" x2="{w}" y2="{TITLE_H}" stroke="{FRAME}" stroke-opacity=".25"/>',
    ]
    for i, col in enumerate(["#ff5f56", "#ffbd2e", "#27c93f"]):
        p.append(f'<circle cx="{PAD + 2 + i * 16}" cy="{TITLE_H / 2 + 1}" r="5" fill="{col}" fill-opacity=".85"/>')
    p.append(
        f'<text class="k-mono" x="{w / 2}" y="{TITLE_H / 2 + 5}" font-size="12.5" fill="{MUTED}" text-anchor="middle">'
        f'daniel@stucaluc: ~/contributions <tspan fill="{ACCENT}">--feed-the-snake</tspan></text>'
    )

    # the snake itself, nested with its own viewBox
    p.append(
        f'<svg x="{PAD}" y="{sy}" width="{vw}" height="{vh}" viewBox="{vx} {vy} {vw} {vh}" overflow="visible">'
        f"{inner}</svg>"
    )

    # footer
    fy = sy + vh + 6
    p.append(f'<line x1="{PAD}" y1="{fy}" x2="{w - PAD}" y2="{fy}" stroke="{FRAME}" stroke-opacity=".2"/>')
    ty = fy + 32
    p.append(
        f'<text class="k-mono" x="{PAD}" y="{ty}" font-size="13" fill="{MUTED}">'
        f'<tspan fill="{ACCENT}">&gt;</tspan> '
        f'<tspan fill="{TEXT}" font-weight="700">{total:,}</tspan> contributions · '
        f'<tspan fill="{TEXT}" font-weight="700">{active}</tspan> active days · '
        f'best day <tspan fill="{TEXT}" font-weight="700">{best["count"]}</tspan>'
        f'<tspan class="k-cur" fill="{ACCENT}"> _</tspan></text>'
    )
    # legend, right aligned, drawn left to right from a computed start
    sq, gap = 10, 3
    legend_w = 34 + len(DOTS) * (sq + gap) + 34
    lx = w - PAD - legend_w
    p.append(f'<text class="k-mono" x="{lx}" y="{ty}" font-size="11" fill="{MUTED}">less</text>')
    x = lx + 34
    for col in DOTS:
        p.append(f'<rect x="{x}" y="{ty - 9}" width="{sq}" height="{sq}" rx="2" fill="{col}"/>')
        x += sq + gap
    p.append(f'<text class="k-mono" x="{x + 4}" y="{ty}" font-size="11" fill="{MUTED}">more</text>')
    p.append(
        f'<text class="k-mono" x="{w - PAD}" y="{fy - 10}" font-size="10" fill="{MUTED}" '
        f'fill-opacity=".7" text-anchor="end">{escape(rng["start"])} → {escape(rng["end"])}</text>'
    )

    p.append("</svg>")
    return "".join(p)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: render_snake_card.py <snake.svg>")
    svg = render(sys.argv[1])
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(svg)
    print(f"wrote {OUT} ({len(svg)} bytes)")
